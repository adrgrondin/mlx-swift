#!/bin/bash

set -euo pipefail

root=$(cd "$(dirname "$0")/.." && pwd)
work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT

generate() {
    local source="$root/Source/Cmlx/mlx/$1"
    local patch_file="$root/cmake/$2"
    local name
    name=$(basename "$source")

    patch -s -f -F 0 -o "$work/$name" "$source" "$patch_file"
    {
        echo '// Generated by tools/generate-patched-mlx.sh. Do not edit.'
        cat "$work/$name"
    } > "$root/Source/Cmlx/mlx-generated/$name"
}

generate mlx/backend/metal/jit_kernels.cpp mlx-nax-split-attention.patch
generate mlx/ops.cpp mlx-quantized-matmul-stream.patch
