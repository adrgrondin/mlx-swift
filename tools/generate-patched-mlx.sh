#!/bin/bash

set -euo pipefail

root=$(cd "$(dirname "$0")/.." && pwd)
source="$root/Source/Cmlx/mlx/mlx/backend/metal/jit_kernels.cpp"
output="$root/Source/Cmlx/mlx-generated/jit_kernels.cpp"
patch_file="$root/cmake/mlx-nax-split-attention.patch"
work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT

patch -s -f -F 0 -o "$work/jit_kernels.cpp" "$source" "$patch_file"
{
    echo '// Generated by tools/generate-patched-mlx.sh. Do not edit.'
    cat "$work/jit_kernels.cpp"
} > "$output"
